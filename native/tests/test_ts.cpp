void check_vec(const rcli::Vec& got, const rcli::Vec& want, double tol, const std::string& what, double floor = 1.0) {
  check::ok(got.size() == want.size(), what + " length");
  for (size_t i = 0; i < want.size() && i < got.size(); ++i)
    check::close(got[i], want[i], tol, what + "[" + std::to_string(i) + "]", floor);
}

void test_acf() {
  check_vec(rcli::acf(s3), acf_s3, 1e-13, "acf(s3)");
  check_vec(rcli::pacf(s3), pacf_s3, 1e-13, "pacf(s3)");
  check_vec(rcli::acf(rcli::Vec(s1.begin(), s1.begin() + 5)), acf_s1_5, 1e-13, "acf(s1[1:5])");
  check_vec(rcli::acf(s7, 3), acf_s7_3, 1e-13, "acf(s7, lag.max = 3)");
  check_vec(rcli::pacf(s7, 3), pacf_s7_3, 1e-13, "pacf(s7, lag.max = 3)");
  check::throws([] { rcli::acf({1.0}); }, "acf(1) too short");
  check::throws([] { rcli::acf({1.0, rcli::kNaN, 2.0}); }, "acf with NA");
}

void test_stl_case(const rcli::StlFit& f, const rcli::Vec& seas, const rcli::Vec& trend, const rcli::Vec& rem,
                   const rcli::Vec& w, const std::string& what) {
  for (size_t k = 0; k < stl_idx.size(); ++k) {
    size_t i = stl_idx[k];
    check::close(f.seasonal[i], seas[k], 1e-8, what + " seasonal[" + std::to_string(i) + "]");
    check::close(f.trend[i], trend[k], 1e-8, what + " trend[" + std::to_string(i) + "]");
    check::close(f.remainder[i], rem[k], 1e-8, what + " remainder[" + std::to_string(i) + "]");
    check::close(f.weights[i], w[k], 1e-8, what + " weights[" + std::to_string(i) + "]");
  }
}

rcli::StlOptions periodic_opts() {
  rcli::StlOptions o;
  o.periodic = true;
  return o;
}

void test_stl() {
  rcli::Vec s6_143(s6.begin(), s6.begin() + 143);
  rcli::StlOptions per;
  per.periodic = true;
  // stl(ts(s6, frequency = 12), s.window = "periodic")
  rcli::StlFit f = rcli::stl(s6, 12, per);
  test_stl_case(f, stl_per_seas, stl_per_trend, stl_per_rem, stl_per_w, "stl periodic");
  bool exact_period = true;
  for (size_t i = 12; i < s6.size(); ++i) exact_period = exact_period && f.seasonal[i] == f.seasonal[i - 12];
  check::ok(exact_period, "stl periodic: seasonal component is exactly periodic");
  // stl(ts(s6, frequency = 12), s.window = 7)
  rcli::StlOptions o7;
  o7.s_window = 7;
  test_stl_case(rcli::stl(s6, 12, o7), stl_7_seas, stl_7_trend, stl_7_rem, stl_7_w, "stl s.window=7");
  // stl(ts(s6[1:143], frequency = 12), s.window = 7, robust = TRUE)
  rcli::StlOptions rob = o7;
  rob.robust = true;
  test_stl_case(rcli::stl(s6_143, 12, rob), stl_rob_seas, stl_rob_trend, stl_rob_rem, stl_rob_w, "stl robust");
  // stl(ts(s6[1:143], frequency = 12), s.window = "periodic", robust = TRUE)
  rcli::StlOptions perrob = per;
  perrob.robust = true;
  test_stl_case(rcli::stl(s6_143, 12, perrob), stl_perrob_seas, stl_perrob_trend, stl_perrob_rem, stl_perrob_w,
                "stl periodic robust");
  // stl(ts(s6, frequency = 12), s.window = 15, s.degree = 1, t.window = 23, t.degree = 0, l.window = 15)
  rcli::StlOptions d1;
  d1.s_window = 15; d1.s_degree = 1; d1.t_window = 23; d1.t_degree = 0; d1.l_window = 15;
  test_stl_case(rcli::stl(s6, 12, d1), stl_deg1_seas, stl_deg1_trend, stl_deg1_rem, stl_deg1_w, "stl degree 1");
  // stl(ts(s6, frequency = 4), s.window = 51): s.window wider than each cycle-subseries (36 values)
  rcli::StlOptions q4;
  q4.s_window = 51;
  test_stl_case(rcli::stl(s6, 4, q4), stl_q4_seas, stl_q4_trend, stl_q4_rem, stl_q4_w, "stl period 4");
  // R: stl(ts(1:24, frequency = 12), "per") -> error "series is not periodic or has less than two periods"
  check::throws([] { rcli::stl(rcli::Vec(24, 1.0), 12, periodic_opts()); }, "stl two periods only");
  check::throws([] { rcli::stl(rcli::Vec(30, 1.0), 1, periodic_opts()); }, "stl period 1");
  check::throws([] { rcli::stl(rcli::Vec(30, 1.0), 12, rcli::StlOptions()); }, "stl without s.window");
}

void test_arima() {
  for (const ArimaCase& c : arima_cases) {
    const std::string L = c.label;
    rcli::ArimaFit f = rcli::arima(*c.x, c.spec);
    check_vec(f.coef, c.coef, 1e-4, L + " coef");
    check_vec(f.se, c.se, 1e-3, L + " se");
    check::close(f.sigma2, c.sigma2, 1e-4, L + " sigma2");
    check::close(f.loglik, c.loglik, 1e-6, L + " loglik");
    check::close(f.aic, c.aic, 1e-6, L + " aic");
    check::ok(f.nobs == c.nobs, L + " nobs");
    check::ok(f.residuals.size() == c.x->size(), L + " residuals length");
    if (f.residuals.size() == c.x->size()) {
      rcli::Vec r = {f.residuals[0], f.residuals[1], f.residuals.back()};
      check_vec(r, c.resid, 1e-3, L + " residuals");
    }
    rcli::ArimaForecast fc = f.forecast(static_cast<int>(c.pred.size()));
    check_vec(fc.mean, c.pred, 1e-4, L + " predict");
    check_vec(fc.se, c.pse, 1e-4, L + " predict se");
  }
  // names: arima(s3, order = c(1,0,1), seasonal = list(order = c(1,0,1), period = 4))$coef names
  rcli::ArimaSpec sp;
  sp.p = 1; sp.q = 1; sp.P = 1; sp.Q = 1; sp.period = 4; sp.method = "CSS";
  rcli::ArimaFit nf = rcli::arima(s3, sp);
  check::ok(nf.coef_names == std::vector<std::string>{"ar1", "ma1", "sar1", "sma1", "intercept"}, "arima coef names");
  check::ok(std::isnan(nf.aic), "arima CSS aic is NA");
  // R: x <- 1.08^(1:60) + 0.1 * sin((0:59) * 1.7); arima(x, c(1,0,0)) -> "non-stationary AR part from CSS"
  check::throws([] {
    rcli::Vec x(60);
    for (int i = 0; i < 60; ++i) x[static_cast<size_t>(i)] = std::pow(1.08, i + 1) + 0.1 * std::sin(i * 1.7);
    rcli::ArimaSpec s;
    s.p = 1;
    rcli::arima(x, s);
  }, "arima non-stationary AR part from CSS");
  check::throws([] { rcli::ArimaSpec s; s.p = 1; rcli::arima({1.0, 2.0}, s); }, "arima too short");
  check::throws([] { rcli::ArimaSpec s; s.p = 1; rcli::Vec x = s1; x[3] = rcli::kNaN; rcli::arima(x, s); },
      "arima NaN");
  check::throws([] { rcli::ArimaSpec s; s.method = "foo"; rcli::arima(s1, s); }, "arima bad method");
  check::throws([] { rcli::ArimaSpec s; s.P = 1; rcli::arima(s1, s); }, "arima seasonal without period");
}

double lag1(const rcli::Vec& x) { return rcli::acf(x, 1)[1]; }

void test_arima_sim() {
  rcli::Rng a(42), b(42);
  rcli::Vec x = rcli::arima_sim(a, 200, {0.5}, {0.3});
  rcli::Vec y = rcli::arima_sim(b, 200, {0.5}, {0.3});
  check::ok(x.size() == 200 && x == y, "arima.sim deterministic for a fixed seed");
  // R: length(arima.sim(list(order = c(1,1,0), ar = 0.7), n = 200)) == 201, first value 0
  rcli::Rng c(1);
  rcli::Vec z = rcli::arima_sim(c, 200, {0.7}, {}, 1.0, 1);
  check::ok(z.size() == 201 && z[0] == 0.0, "arima.sim d = 1: length n + 1 starting at 0");
  rcli::Rng c2(1);
  rcli::Vec z2 = rcli::arima_sim(c2, 200, {0.7}, {}, 1.0, 2);
  check::ok(z2.size() == 202 && z2[0] == 0.0 && z2[1] == 0.0, "arima.sim d = 2: length n + 2");
  // default n.start for ar = 0.5: p + q + ceiling(6 / log(2)) = 1 + 0 + 9 = 10
  rcli::Rng d1(7), d2(7);
  check::ok(rcli::arima_sim(d1, 50, {0.5}, {}) == rcli::arima_sim(d2, 50, {0.5}, {}, 1.0, 0, 10),
            "arima.sim default n.start = p + q + ceiling(6/log(minroots))");
  // long AR(1): sample lag-1 autocorrelation near phi
  rcli::Rng e(3);
  check::close(lag1(rcli::arima_sim(e, 20000, {0.7}, {})), 0.7, 0.03, "arima.sim AR(1) acf(1) ~ 0.7");
  // MA(1) theta = 0.5: rho(1) = 0.5 / 1.25 = 0.4
  rcli::Rng g(4);
  check::close(lag1(rcli::arima_sim(g, 20000, {}, {0.5})), 0.4, 0.05, "arima.sim MA(1) acf(1) ~ 0.4");
  // innovations sd: white noise with sd = 2 has variance ~ 4
  rcli::Rng h(5);
  rcli::Vec wn = rcli::arima_sim(h, 20000, {}, {}, 2.0);
  double m = 0.0, v = 0.0;
  for (double t : wn) m += t;
  m /= wn.size();
  for (double t : wn) v += (t - m) * (t - m);
  v /= (wn.size() - 1);
  check::close(v, 4.0, 0.05, "arima.sim sd = 2 variance ~ 4");
  // R: arima.sim(list(ar = 1), 10) -> "'ar' part of model is not stationary"
  check::throws([] { rcli::Rng r(1); rcli::arima_sim(r, 10, {1.0}, {}); }, "arima.sim ar = 1 not stationary");
  check::throws([] { rcli::Rng r(1); rcli::arima_sim(r, 10, {0.5, 0.6}, {}); },
      "arima.sim ar = c(.5,.6) not stationary");
  check::throws([] { rcli::Rng r(1); rcli::arima_sim(r, 0, {}, {}); }, "arima.sim n = 0");
  // R: arima.sim(list(ar = 0.5, ma = 0.3), 10, n.start = 1) -> "burn-in 'n.start' must be as long as 'ar + ma'"
  check::throws([] { rcli::Rng r(1); rcli::arima_sim(r, 10, {0.5}, {0.3}, 1.0, 0, 1); }, "arima.sim n.start too short");
}

