void check_spline(const rcli::CubicSpline& s, const Vec& x, const double (*ref)[10], const std::string& name) {
  for (int d = 0; d <= 3; ++d)
    for (size_t i = 0; i < x.size(); ++i)
      check::close(s.deriv(x[i], d), ref[d][i], 1e-13,
                   "splinefun(x, y, method='" + name + "')(" + std::to_string(x[i]) + ", deriv=" + std::to_string(d) + ")");
}
